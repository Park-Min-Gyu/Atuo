# -*- coding: utf-8 -*-
"""
yl_hex.py : 연구실 YL_HEX_V6_PURE_2mm.tcl (HyperMesh 헥사 메시)을 파이프라인 메시 단계로 실행

  원본 스크립트(hypermesh/YL_HEX/YL_HEX_V6_PURE_2mm.tcl)는 그대로 둔다 (HyperMesh 에서 File > Run 으로 단독 실행 가능).
  원본은 마지막 줄에서 설정 창(ylh6_launch_gui)을 띄우므로, 실행할 때마다 그 한 줄만 뺀 복사본을 만들어
  hmbatch 로 '헥사 + 3D' 모드(ylh6_run_3d : Multi-Solid Map, quads_only = 순수 헥사)를 바로 부른다.

  합격 조건 : Abaqus INP 가 나왔고, 헥사가 1 개 이상, 웨지(penta) 0 개, 매핑 안 된 솔리드 0 개
  -> 아니면 FAIL 을 돌려준다. 헥사 전용이라 Tetra 메셔로 넘어가지 않고, 그 모델은 메시 실패로 끝난다.
  주의 : SolidMap 은 '매핑 가능한' 솔리드에서만 헥사를 만든다. 공극·필렛이 많은 부싱 솔리드는
         통째로는 매핑이 안 되는 경우가 많다 (원본 스크립트도 '솔리드를 나눠라'고 안내한다).
"""
from __future__ import annotations

import re
from pathlib import Path

from core import runners


def _engine_copy(src: Path, dest: Path) -> Path:
    txt = Path(src).read_text(encoding="utf-8", errors="ignore").replace("\r\n", "\n")
    txt2, n = re.subn(r"\n[ \t]*ylh6_launch_gui[ \t]*\n?\s*$", "\n# (batch: GUI launch removed)\n", txt)
    if n == 0:
        raise RuntimeError(f"{src} 끝에서 'ylh6_launch_gui' 를 찾지 못함 (YL_HEX 스크립트가 맞는지 확인)")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(txt2.encode("utf-8"))
    return dest


WRAPPER = r'''# auto-generated by core/yl_hex.py
set ::YL_BATCH 1
# hmbatch 에는 대화창이 없다 -> 혹시 불리면 '아니오'로 답함 (원본 스크립트의 확인창 대비)
proc tk_messageBox {args} { return "no" }
set ST "%(status)s"
proc ylx_status {pairs} {
    if {[catch {open $::ST w} fh]} { return }
    fconfigure $fh -encoding utf-8
    foreach {k v} $pairs { puts $fh "$k=[string map [list "\n" " | " "\r" ""] $v]" }
    close $fh
}
ylx_status [list STATUS RUNNING MESSAGE "HyperMesh stopped during import"]
catch { hm_answernext yes }
catch { *deletemodel }
set src "%(geom)s"
set ext [string tolower [file extension $src]]
if {[catch {
    if {$ext eq ".hm"} {
        catch { hm_answernext yes }
        *readfile $src
    } else {
        *geomimport "auto_detect" $src "CleanupTol=-0.01" "CreationType=Parts" "DoNotMergeEdges=off" \
            "ImportBlanked=off" "SplitComponents=Part" "TargetUnits=CAD units"
    }
} err]} {
    ylx_status [list STATUS FAIL MESSAGE "import failed: $err"]
    catch { *quit 1 }
}
ylx_status [list STATUS RUNNING MESSAGE "HyperMesh stopped during YL_HEX 3D"]
source "%(engine)s"
set cfg [ylh6_default_params]
foreach {k v} {family hex dim 3d mode hex select_mode all quad_fallback 0 save_hm 1 export_inp 1 delete_2d 1} {
    dict set cfg $k $v
}
dict set cfg out_dir  "%(out_dir)s"
dict set cfg out_name "%(name)s"
dict set cfg elem_type "%(etype)s"
set res [dict create status FAIL msg "not run"]
set rc [catch { set res [ylh6_run_3d $cfg] } err]
if {$rc} { set res [dict create status FAIL msg "script error: $err"] }
set n_hex 0; set n_penta 0; set n_sol 0; set n_unmap 0
catch { set n_hex   [ylh6_count_elems {hex8 hex20}] }
catch { set n_penta [ylh6_count_elems {penta6 penta15}] }
catch {
    *clearmark solids 1; *createmark solids 1 "all"
    set sids [hm_getmark solids 1]; *clearmark solids 1
    set n_sol [llength $sids]
    foreach s $sids { if {[ylh6_solid_3d_count $s] == 0} { incr n_unmap } }
}
set inp "%(out_dir)s/%(name)s.inp"
ylx_status [list STATUS [dict get $res status] N_HEX $n_hex N_PENTA $n_penta N_SOLIDS $n_sol N_UNMAP $n_unmap \
    INP [expr {[file exists $inp] ? $inp : ""}] MESSAGE [dict get $res msg]]
catch { *quit 1 }
'''


def park_geometry_hm(out_dir: Path, base: str) -> str:
    """[v27.6] SolidMap 이 헥사를 못 만들었을 때 HyperMesh 가 저장한 <base>.hm 에는 CAD 형상만 있고 메시가 없다.
    이 파일을 메시 파일로 오해하지 않게 이름을 <base>_SolidMap_geometry_only.hm 으로 바꾼다. 반환: 새 경로(없으면 "")"""
    src = Path(out_dir) / f"{base}.hm"
    if not src.exists():
        return ""
    dst = Path(out_dir) / f"{base}_SolidMap_geometry_only.hm"
    try:
        if dst.exists():
            dst.unlink()
        src.rename(dst)
        return runners._p(dst)
    except OSError:          # HyperMesh 에서 열려 있으면 이름을 못 바꿈 -> 그대로 둠
        return runners._p(src)


def run_hex(hm_cfg: dict, script: Path, geom: Path, out_dir: Path, base: str, elem_size: float,
            elem_type: str = "C3D8H") -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    log_dir = out_dir / "_logs"
    log_dir.mkdir(exist_ok=True)
    status = log_dir / "hex_status.txt"
    if status.exists():
        status.unlink()
    eng = _engine_copy(script, out_dir / "_engine_hex" / "YL_HEX_V6_batch.tcl")
    for old in (out_dir / f"{base}.inp", out_dir / f"{base}_hm.inp"):
        if old.exists():
            old.unlink()
    wrapper = log_dir / "hex_wrapper.tcl"
    wrapper.write_text(WRAPPER % {"status": runners._p(status), "geom": runners._p(geom), "engine": runners._p(eng),
                                  "out_dir": runners._p(out_dir), "name": base, "etype": elem_type}, encoding="utf-8")
    cmd = [hm_cfg["exe"]] + list(hm_cfg.get("args", ["-tcl"])) + [runners._p(wrapper)]
    rc, dt = runners._run(cmd, log_dir, log_dir / "hm_console_HEX.log", float(hm_cfg.get("timeout_min", 60)) * 60)
    r = {}
    if status.exists():
        for line in status.read_text(encoding="utf-8", errors="ignore").splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                r[k.strip()] = v.strip()
    n_hex = int(float(r.get("N_HEX") or 0))
    n_penta = int(float(r.get("N_PENTA") or 0))
    n_unmap = int(float(r.get("N_UNMAP") or 0))
    inp = r.get("INP", "")
    why = []
    if not r:
        why.append(f"hex 결과(hex_status.txt)가 없음 (hmbatch rc={rc}) -> _logs/hm_console_HEX.log 확인")
    elif r.get("STATUS") == "RUNNING":
        why.append(f"HyperMesh 가 도중에 종료됨 ({r.get('MESSAGE', '')})")
    if r and n_hex == 0:
        why.append("헥사 0개 (솔리드가 없거나 매핑할 수 없는 형상)")
    if n_unmap > 0:
        why.append(f"매핑 안 된 솔리드 {n_unmap}/{r.get('N_SOLIDS')}개 (형상을 매핑 가능한 블록으로 나눠야 함)")
    if n_penta > 0:
        why.append(f"웨지(penta) {n_penta}개 섞임 (순수 헥사 아님)")
    if r and n_hex > 0 and not (inp and Path(inp).exists()):
        why.append("Abaqus INP 가 안 나옴 (음의 Jacobian 요소가 있으면 원본 스크립트가 INP 를 쓰지 않음)")
    ok = not why
    out_inp = out_dir / f"{base}_hm.inp"
    if ok:
        Path(out_inp).write_bytes(Path(inp).read_bytes())
    geom_hm = "" if ok else park_geometry_hm(out_dir, base)
    msg = "" if ok else "YL_HEX : " + "; ".join(why)
    st = {"STATUS": "OK" if ok else "FAIL", "MESSAGE": msg, "ALGO": "YL_HEX_V6", "HEX_STATUS": r.get("STATUS", ""),
          "N_HEX": n_hex, "N_PENTA": n_penta, "N_SOLIDS": r.get("N_SOLIDS", ""), "N_UNMAP": n_unmap,
          "N_TET": n_hex, "N_TRIA": 0, "ELEM_SIZE": 2.0, "ELEM_SIZE_ASKED": elem_size,
          "INP_FILE": runners._p(out_inp) if ok else "", "returncode": rc, "elapsed_s": round(dt, 1),
          "GEOM_ONLY_HM": geom_hm}
    (out_dir / "hm_status.txt").write_text("".join(f"{k}={v}\n" for k, v in st.items()), encoding="utf-8")
    st["LOG_TAIL"] = [f"hex: {r.get('MESSAGE', '')[:400]}"] if r else runners._tail(log_dir / "hm_console_HEX.log", 10)
    return st
